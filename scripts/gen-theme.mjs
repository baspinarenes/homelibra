// `pnpm gen:theme`: writes packages/ui/src/theme.css from packages/ui/src/lib/tokens.ts,
// so Tailwind classes (Uniwind) and the TypeScript tokens never disagree.
// `pnpm gen:theme --check` fails when the file on disk is out of date (part of `pnpm check`).
//
// What a class is called comes from the token's name:
//   palette.light.page  → bg-page, text-page, border-page …  (light and dark per theme)
//   space.md            → p-md, gap-md, mx-md …
//   radius.control      → rounded-control
//   fonts.serif         → font-serif
//   type.body           → type-body (face, size, line and spacing in one class)
//   shadows.light.card  → shadow-card

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { fonts, palette, radius, shadows, space, type } from '../packages/ui/src/lib/tokens.ts';

const out = fileURLToPath(new URL('../packages/ui/src/theme.css', import.meta.url));

// Token names are ASCII identifiers, so the case shift is ASCII too: Turkish rules
// would turn chipInk into chip-ınk.
const kebab = (name) => name.replace(/[A-Z]/g, (c) => `-${String.fromCharCode(c.charCodeAt(0) + 32)}`);
const px = (n) => (n === 999 ? '9999px' : `${n}px`);

export function themeCss() {
  const lines = [
    '/* Generated by `pnpm gen:theme` from src/lib/tokens.ts. Do not edit. */',
    '',
    '@theme {',
    ...Object.entries(space).map(([k, v]) => `  --spacing-${kebab(k)}: ${px(v)};`),
    ...Object.entries(radius).map(([k, v]) => `  --radius-${kebab(k)}: ${px(v)};`),
    ...Object.entries(fonts).map(([k, v]) => `  --font-${kebab(k)}: '${v}';`),
    '}',
    '',
    '@layer theme {',
    '  :root {',
  ];
  for (const scheme of ['light', 'dark']) {
    lines.push(`    @variant ${scheme} {`);
    for (const [k, v] of Object.entries(palette[scheme])) lines.push(`      --color-${kebab(k)}: ${v};`);
    lines.push('    }');
  }
  lines.push('  }', '}', '');
  for (const [k] of Object.entries(shadows.light)) {
    lines.push(`@utility shadow-${kebab(k)} {`);
    lines.push(`  box-shadow: ${shadows.light[k]};`);
    lines.push(`  @variant dark {`, `    box-shadow: ${shadows.dark[k]};`, '  }');
    lines.push('}', '');
  }
  for (const [k, v] of Object.entries(type)) {
    lines.push(`@utility type-${kebab(k)} {`);
    if (v.fontFamily) lines.push(`  font-family: '${v.fontFamily}';`);
    if (v.fontSize) lines.push(`  font-size: ${px(v.fontSize)};`);
    if (v.lineHeight) lines.push(`  line-height: ${px(v.lineHeight)};`);
    if (v.letterSpacing) lines.push(`  letter-spacing: ${px(v.letterSpacing)};`);
    lines.push('}', '');
  }
  return lines.join('\n');
}

// Tailwind only generates a class it finds written whole in the source: `text-${name}`
// never appears, so code that picks a class by a token's name picks it from these maps.
export function classesTs() {
  const map = (name, prefix, keys) => [
    `export const ${name} = {`,
    ...keys.map((k) => `  ${k}: '${prefix}${kebab(k)}',`),
    '} as const;',
    '',
  ];
  const colors = Object.keys(palette.light);
  return [
    '// Generated by `pnpm gen:theme` from tokens.ts. Do not edit.',
    '// Whole class names per token, for code that picks a class by name: Tailwind',
    '// generates only classes it finds written whole, never `text-${name}`.',
    '',
    ...map('textColor', 'text-', colors),
    ...map('bgColor', 'bg-', colors),
    ...map('borderColor', 'border-', colors),
    ...map('typeClass', 'type-', Object.keys(type)),
  ].join('\n');
}

const outputs = [
  [out, themeCss],
  [fileURLToPath(new URL('../packages/ui/src/lib/classes.ts', import.meta.url)), classesTs],
];

if (import.meta.url === `file://${process.argv[1]}`) {
  for (const [file, make] of outputs) {
    const text = make();
    const name = file.slice(file.indexOf('packages/'));
    if (process.argv.includes('--check')) {
      let current = '';
      try {
        current = readFileSync(file, 'utf8');
      } catch {
        // missing counts as stale
      }
      if (current !== text) {
        console.error(`${name} is out of date with tokens.ts. Run: pnpm gen:theme`);
        process.exit(1);
      }
    } else {
      writeFileSync(file, text);
      console.log(`wrote ${name}`);
    }
  }
}
